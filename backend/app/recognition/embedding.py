"""
EmbeddingGenerator — produces L2-normalised face embeddings via InsightFace/ArcFace.

The embedding is generated by the actual recognition model — nothing is faked.
Embedding dimensionality is read from the loaded model, not hard-coded.
"""

from __future__ import annotations

import logging
import time

import numpy as np

from backend.app.recognition.errors import EmbeddingError
from backend.app.recognition.model_manager import ModelManager

logger = logging.getLogger("facenexa.embedding")


class EmbeddingGenerator:
    """Generate and normalise face embeddings from aligned 112×112 face images."""

    def generate(self, aligned_face: np.ndarray) -> tuple[np.ndarray, float]:
        """Produce an L2-normalised embedding.

        Args:
            aligned_face: BGR image, ideally 112×112.

        Returns:
            (embedding, elapsed_ms)

        Raises:
            EmbeddingError: if the model is unavailable or inference fails.
        """
        manager = ModelManager.get_instance()
        if not manager.is_ready or manager.app is None:
            raise EmbeddingError(detail="Recognition model not loaded.")

        # Find the recognition model inside the FaceAnalysis app
        rec_model = None
        for model in manager.app.models:
            if getattr(model, "taskname", "") == "recognition":
                rec_model = model
                break

        if rec_model is None:
            raise EmbeddingError(detail="Recognition model not found in loaded models.")

        t0 = time.perf_counter()
        try:
            # InsightFace recognition models expect a face object with a
            # normed_embedding or we can call the model directly.
            # The cleanest approach: use ``rec_model.get(img, face)`` where
            # *face* has a ``kps`` attribute, OR call the lower-level forward.
            # We use a lightweight wrapper that builds what the model expects.

            embedding = self._forward(rec_model, aligned_face)
        except Exception as exc:
            raise EmbeddingError(detail=str(exc)) from exc

        elapsed_ms = (time.perf_counter() - t0) * 1000.0
        return embedding, elapsed_ms

    # ── Internal ──────────────────────────────────────────────────────

    @staticmethod
    def _forward(rec_model, aligned_face: np.ndarray) -> np.ndarray:
        """Run the recognition model and return an L2-normalised embedding."""
        import cv2

        # Ensure correct size
        if aligned_face.shape[:2] != (112, 112):
            aligned_face = cv2.resize(aligned_face, (112, 112))

        # Prepare input: HWC → CHW, BGR, float32, add batch dim
        img = aligned_face.astype(np.float32)

        # InsightFace models typically accept (1, 3, 112, 112) after
        # normalisation.  The exact preprocessing mirrors ``rec_model.get``.
        blob = cv2.dnn.blobFromImage(
            img,
            scalefactor=1.0 / 127.5,
            size=(112, 112),
            mean=(127.5, 127.5, 127.5),
            swapRB=True,
        )

        # Run ONNX session
        session = rec_model.session
        input_name = session.get_inputs()[0].name
        outputs = session.run(None, {input_name: blob})
        raw_embedding = outputs[0].flatten().astype(np.float64)

        # L2 normalise
        norm = np.linalg.norm(raw_embedding)
        if norm < 1e-10:
            logger.warning("Embedding has near-zero norm — returning raw.")
            return raw_embedding.astype(np.float32)

        normalised = (raw_embedding / norm).astype(np.float32)
        return normalised
